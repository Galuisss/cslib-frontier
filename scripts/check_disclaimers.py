#!/usr/bin/env python3
"""Keep the limitations that docstrings state tracked by an issue or a baseline entry (#5293).

Usage: python3 scripts/check_disclaimers.py [--base REF | --all | --report | --list [PREFIX]]
           [--enforce] [--update-baseline [--allow-increase]] [--root DIR] [--baseline FILE]

This checks the rule "A stated limitation is tracked" of policy/taste.md (#6027). A docstring that
says what is not proved, what is assumed or what is left to the caller is welcome, but it does not
resolve the gap: a theorem can be much weaker than its name while its docstring honestly says so,
and then nothing but a reader of the prose finds the gap again.

A *disclaimer* is a sentence of a declaration docstring (`/-- … -/`) or module docstring
(`/-! … -/`) of a Lean file under `ROOTS` (for now `CslibFrontier/Crypto`) that matches one of
`PATTERNS`, case-insensitively, after its whitespace is collapsed. Ordinary comments (`--`,
`/- … -/`), strings and code are not read. A docstring is cut into sentences at blank lines, at
list items and headings, and after `.`, `!` or `?` followed by whitespace and anything but a
lower-case letter or a digit; a heading such as `## What is not proved`, followed by a blank line,
is a sentence of its own, so a section of limitations is one disclaimer plus those of its items.
The cut is approximate (an abbreviation outside `ABBREVIATIONS` followed by a capital ends a
sentence early), which changes only how much text a disclaimer shows.

A disclaimer is *tracked* when

* its docstring contains an issue or pull-request number `#NNNN` (three to five digits), anywhere
  in the docstring, or
* the declaration that its docstring is attached to has an entry in
  `scripts/security_premises_baseline.json` or `scripts/reduction_witnesses_baseline.json`
  (`RECORDS`), or, for a module docstring, some entry of those files names the module.

The declaration a docstring is attached to is found in the source, with the declaration reader of
`scripts/check_encoding_readability.py`: it is the declaration whose command the text after the
docstring belongs to, so a docstring of a structure field or a constructor is attached to its
structure or inductive type, and its name is the written name inside the enclosing `namespace`s.
This is approximate. A docstring before anything but a theorem, lemma, definition, abbreviation,
instance, structure, class, inductive type, opaque constant or axiom (a `macro`, a `notation`, an
`alias`, a declaration generated by a command) is attached to nothing, and so is one that the
reader cannot parse; an anonymous instance has no name to look up. The check does not judge whether
the cited issue or the entry is about the limitation: an issue number that the docstring cites for
another reason tracks every disclaimer of that docstring, and an entry for one premise of a theorem
tracks every disclaimer of its docstring. Review reads that.

`scripts/disclaimers_baseline.json` records the untracked disclaimers, one per line, as
`{"path:digest": {"sentence": text}}`, with `"count": n` when the sentence occurs untracked `n > 1`
times in the file. The digest is the first 12 hexadecimal digits of the SHA-256 of the sentence
with its whitespace collapsed and its case folded, so moving a sentence, rewrapping it or editing
the text around it keeps its entry, and rewording it does not. The sentence is stored for readers
and must match the digest. The baseline is a list of debts to pay down, not a list of exemptions:
an entry says that a limitation is stated and nothing tracks it yet. Pay one down by proving the
missing part, by renaming or restating the declaration so that the limitation is gone, or by
opening an issue and citing its number in the docstring; then remove the entry.

In a module that the change touches (adds, modifies or deletes, against the merge base of `--base`,
default `origin/main`, and the working tree, as `scripts/check_changed_files.py` computes it), an
untracked disclaimer without an entry is *new*, and an entry whose sentence is gone or is now
tracked is *stale*. A change that adds or modifies this checker or its baseline is compared in
every module. Differences in other modules are printed as a notice: a change can cause them without
touching those modules, for example by removing an entry of the other two baselines. Pull requests
run this mode. `--all` compares every module. `--report` prints every difference and always
succeeds; merge groups and pushes to `main` run it. `--list [PREFIX]` ignores the baseline and
prints every disclaimer in the files under the path PREFIX with how it is tracked; it always
succeeds. `--update-baseline` removes the stale entries of the compared modules; it refuses to
record a new disclaimer unless `--allow-increase` is given, as for a module that moves, so that new
debt is added on purpose and shows in review as an added line.
`--update-baseline --all --allow-increase` regenerates the whole baseline.

**Report only, for now.** Without `--enforce` the check prints its findings and exits 0. With
`--enforce`, a new disclaimer or a stale entry in a compared module exits 1. CI does not pass
`--enforce` yet; passing it in the pull-request step of `.github/workflows/lean_action_ci.yml` and
in its mirror in `scripts/full_check.py` turns enforcement on. A malformed baseline exits nonzero
in either mode.

The check is wording-based. A limitation phrased in words that `PATTERNS` does not list is not
seen, a listed phrase used in another sense is flagged, and a docstring that says nothing about a
weak statement passes. `scripts/check_security_premises.py` and
`scripts/check_reduction_witnesses.py` read the statements themselves; this check only keeps the
admissions that authors do write from being the last word. It reads only the sources and the three
baselines: it needs no build outputs.
"""

from __future__ import annotations

import argparse
from bisect import bisect_right
from collections import Counter
from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import check_encoding_readability as cer  # noqa: E402
from check_hygiene import extract_docstrings  # noqa: E402

# The directories whose Lean files are read. Widen the check by adding roots.
ROOTS = ("CslibFrontier/Crypto",)
BASELINE = "scripts/disclaimers_baseline.json"
# The baselines whose entries track a declaration: objects from declaration names to entries with
# a `module` path.
RECORDS = ("scripts/security_premises_baseline.json", "scripts/reduction_witnesses_baseline.json")
# A change to the checker or its baseline is compared in every module, so that its own CI run sees
# whether the whole library still matches.
CHECKER_FILES = frozenset({"scripts/check_disclaimers.py", BASELINE})
UPDATE = "python3 scripts/check_disclaimers.py --update-baseline"
RULE = "policy/taste.md, A stated limitation is tracked"

# The phrases that make a sentence a disclaimer. Each is matched between word boundaries, ignoring
# case, in a sentence whose whitespace is collapsed. The list was tuned on `CslibFrontier/Crypto`:
# `supplied by the caller` was dropped (it mostly described ordinary parameters), and
# `does not claim agreement` is left out (the modules that follow a published standard say that
# they claim nothing about its future revisions).
PATTERNS = (
    r"do(?:es)? not (?:yet )?(?:prove|establish|certify|claim(?! agreement))",
    r"(?:is|are) not (?:yet )?(?:proved|certified|established)",
    r"not proved here",
    r"no (?:strict-)?(?:PPT|efficiency) (?:certificate|witness)",
    r"assum(?:es|ing) (?:that )?the reduction",
    r"caller (?:supplies|provides)",
    r"left to the caller",
    r"not asserted",
    r"(?:as|remains?) a hypothesis",
    r"remains? open",
    r"limitations?",
    r"is not tracked",
    r"not a security theorem",
    r"stand-in",
)
DISCLAIMER = re.compile(r"(?<![\w-])(?:" + "|".join(PATTERNS) + r")(?![\w-])", re.I)
# An issue or pull-request number: `#123` to `#12345`.
ISSUE = re.compile(r"(?<![\w&#])#\d{3,5}(?![\w])")
# Abbreviations whose period does not end a sentence.
ABBREVIATIONS = ("e.g.", "i.e.", "cf.", "vs.", "resp.", "p.", "pp.", "Sec.", "Thm.", "Def.", "Eq.",
                 "Fig.", "et al.")
# Where a docstring is cut into sentences: a blank line, the start of a list item or a heading,
# and whitespace after a sentence end that is not an abbreviation and that anything but a
# lower-case letter or a digit follows.
BREAK = re.compile(
    r"\n[ \t]*\n\s*"
    r"|\n(?=[ \t]*(?:[-*+] |\d+\. |#{1,6} ))"
    r"|(?:(?<=[.!?])|(?<=[.!?]\*\*)|(?<=[.!?][)\"”’]))"
    + "".join(rf"(?<!\b{re.escape(a)})" for a in ABBREVIATIONS)
    + r"\s+(?=[^\sa-z\d])")
LIST_MARKER = re.compile(r"(?:[-*+]|\d+\.) ")
MODULE_DOC = "(module docstring)"


@dataclass(frozen=True)
class Hit:
    """A disclaimer: its file and line, the declaration its docstring is attached to (`MODULE_DOC`
    for a module docstring, the empty string when the reader finds none), the sentence with its
    whitespace collapsed, and how it is tracked: an issue number such as `#5293`, `baseline entry`
    or the empty string."""
    path: str
    line: int
    declaration: str
    sentence: str
    tracked: str

    @property
    def key(self) -> str:
        return f"{self.path}:{digest(self.sentence)}"


def digest(sentence: str) -> str:
    """The digest of a sentence: stable under rewrapping and change of case."""
    normal = " ".join(sentence.split()).casefold()
    return hashlib.sha256(normal.encode("utf-8")).hexdigest()[:12]


def sentences(doc: str) -> list[tuple[int, str]]:
    """The sentences of a docstring body as `(offset, text)`, whitespace collapsed and the marker
    of a list item removed."""
    found, start = [], 0
    for cut in [*BREAK.finditer(doc), None]:
        piece = doc[start:cut.start() if cut else len(doc)]
        text = " ".join(piece.split())
        if marker := LIST_MARKER.match(text):
            text = text[marker.end():]
        if text:
            found.append((start + len(piece) - len(piece.lstrip()), text))
        start = cut.end() if cut else len(doc)
    return found


Reader = tuple[list[int], list[tuple[int, str]]]


def declaration_names(text: str) -> Reader:
    """The start offset of each command that the declaration reader yields and, in the same order,
    its end offset with the full name of the declaration it declares (the empty string when it
    declares none or has no name)."""
    starts, commands = [], []
    for command in cer.commands(text):
        name = command.parts()[0] if command.keyword in cer.DECLARATIONS else None
        if name and name.startswith("_root_."):
            name = name.removeprefix("_root_.")
        elif name:
            name = ".".join((*command.scope.namespace, name))
        starts.append(command.start)
        commands.append((command.end, name or ""))
    return starts, commands


def attached(text: str, end: int, reader: Reader) -> str:
    """The declaration whose command the first text after offset `end` belongs to, if any."""
    while end < len(text) and text[end].isspace():
        end += 1
    starts, commands = reader
    index = bisect_right(starts, end) - 1
    if index < 0:
        return ""
    command_end, name = commands[index]
    return name if end < command_end else ""


def load_records(root: Path) -> tuple[set[str], set[str]]:
    """The declarations and the modules that have an entry in one of `RECORDS`."""
    names, modules = set(), set()
    for rel in RECORDS:
        path = root / rel
        if not path.exists():
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        names |= set(data)
        modules |= {entry["module"] for entry in data.values()
                    if isinstance(entry, dict) and isinstance(entry.get("module"), str)}
    return names, modules


def module_hits(rel: str, text: str, names: set[str], modules: set[str]) -> list[Hit]:
    """The disclaimers of a Lean source file, in order."""
    hits, reader = [], None
    for start, doc in extract_docstrings(text):
        found = [(offset, s) for offset, s in sentences(doc) if DISCLAIMER.search(s)]
        if not found:
            continue
        issue = ISSUE.search(doc)
        if text[start - 3:start] == "/-!":
            declaration = MODULE_DOC
            recorded = rel in modules
        else:
            if reader is None:
                try:
                    reader = declaration_names(text)
                except ValueError:  # the reader cannot parse the file: attach nothing
                    reader = ([], [])
            declaration = attached(text, start + len(doc) + 2, reader)
            recorded = declaration in names
        tracked = issue[0] if issue else "baseline entry" if recorded else ""
        hits += [Hit(rel, text.count("\n", 0, start + offset) + 1, declaration, sentence, tracked)
                 for offset, sentence in found]
    return hits


def scan(root: Path, prefix: str = "") -> list[Hit]:
    """The disclaimers of the Lean files under `ROOTS` whose path starts with `prefix`."""
    names, modules = load_records(root)
    hits = []
    for top in ROOTS:
        for path in sorted((root / top).rglob("*.lean")):
            rel = path.relative_to(root).as_posix()
            if rel.startswith(prefix):
                hits += module_hits(rel, path.read_text(encoding="utf-8"), names, modules)
    return hits


def untracked(hits: list[Hit]) -> dict[str, list[Hit]]:
    """The untracked disclaimers by baseline key."""
    found: dict[str, list[Hit]] = {}
    for hit in hits:
        if not hit.tracked:
            found.setdefault(hit.key, []).append(hit)
    return found


def key_path(key: str) -> str:
    return key.rsplit(":", 1)[0]


def valid_entry(key: str, value: object) -> bool:
    return (isinstance(value, dict) and set(value) <= {"sentence", "count"}
            and isinstance(value.get("sentence"), str)
            and key == f"{key_path(key)}:{digest(value['sentence'])}"
            and ("count" not in value or (type(value["count"]) is int and value["count"] > 1)))


def load_baseline(path: Path) -> dict[str, dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        sys.exit(f"{path}: expected a JSON object")
    bad = [key for key, value in data.items() if not valid_entry(key, value)]
    if bad:
        sys.exit(f"{path}: expected entries " '"path:digest": {"sentence": text}, optionally with '
                 '"count": n > 1, where the digest is that of the sentence; regenerate the entry '
                 f"with `{UPDATE}` instead of editing it: {', '.join(bad[:5])}")
    return data


def baseline_text(entries: dict[str, dict]) -> str:
    """One entry per line, sorted by path, so concurrent edits rarely touch the same lines."""
    lines = [f" {json.dumps(key, ensure_ascii=False)}: "
             + json.dumps({f: entries[key][f] for f in ("sentence", "count") if f in entries[key]},
                          ensure_ascii=False)
             for key in sorted(entries)]
    return "{\n" + ",\n".join(lines) + ("\n" if lines else "") + "}\n"


@dataclass(frozen=True)
class Problems:
    """Differences from the baseline: untracked disclaimers that it does not record, and entries
    that no longer match as `(key, entry, reason)`."""
    new: list[Hit]
    stale: list[tuple[str, dict, str]]

    def __bool__(self) -> bool:
        return bool(self.new or self.stale)

    def __len__(self) -> int:
        return len(self.new) + len(self.stale)


def compare(hits: list[Hit], baseline: dict[str, dict], paths: set[str] | None) -> Problems:
    """The differences in the modules `paths` (every module when `None`)."""
    def scoped(path: str) -> bool:
        return paths is None or path in paths
    current = untracked(hits)
    tracked_keys = {hit.key for hit in hits if hit.tracked}
    new, stale = [], []
    for key, rows in current.items():
        recorded = baseline.get(key, {}).get("count", 1) if key in baseline else 0
        if scoped(key_path(key)) and len(rows) > recorded:
            new += rows[recorded:]
    for key, entry in sorted(baseline.items()):
        count, recorded = len(current.get(key, ())), entry.get("count", 1)
        if not scoped(key_path(key)) or count >= recorded:
            continue
        reason = (f"occurs untracked {count} time(s), not {recorded}" if count
                  else "now tracked" if key in tracked_keys else "the sentence is gone")
        stale.append((key, entry, reason))
    return Problems(sorted(new, key=lambda hit: (hit.path, hit.line)), stale)


def outside(everywhere: Problems, here: Problems) -> Problems:
    """The differences of `everywhere` that are not in `here`."""
    return Problems([p for p in everywhere.new if p not in here.new],
                    [p for p in everywhere.stale if p not in here.stale])


def update(hits: list[Hit], baseline: dict[str, dict], paths: set[str] | None) -> dict[str, dict]:
    """The baseline with the entries of the modules `paths` (all when `None`) matching the
    untracked disclaimers."""
    updated = {key: entry for key, entry in baseline.items()
               if paths is not None and key_path(key) not in paths}
    for key, rows in untracked(hits).items():
        if paths is None or key_path(key) in paths:
            updated[key] = {"sentence": rows[0].sentence,
                            **({"count": len(rows)} if len(rows) > 1 else {})}
    return updated


def describe(hit: Hit) -> list[str]:
    where = f": {hit.declaration}" if hit.declaration else ""
    return [f"  {hit.path}:{hit.line}{where}", f"    {hit.sentence}"]


def report(problems: Problems) -> str:
    out = []
    if problems.new:
        out += ["Docstrings that state a limitation which nothing tracks. A sentence saying what "
                "is not proved, what is assumed or what is left to the caller makes the gap "
                f"known; it does not close it ({RULE}). Close it: prove the missing part, or "
                "rename and restate the declaration so that it says what it proves. Otherwise "
                "track it: cite the issue that owns the gap as `#NNNN` in the same docstring, or "
                "give the declaration its entry in the security-premise or reduction-witness "
                "baseline when one of those checks covers it. Recording new debt in "
                f"{BASELINE} (`{UPDATE} --allow-increase`) is the last resort and shows in "
                "review.", ""]
        for hit in problems.new:
            out += describe(hit)
    if problems.stale:
        out += ([""] if out else []) + [
            "Baseline entries that no longer match an untracked disclaimer; remove them in the "
            f"same change (`{UPDATE}`):"]
        out += [f"  {key} ({reason}): {entry['sentence']}" for key, entry, reason in problems.stale]
    return "\n".join(out)


def listing(hits: list[Hit]) -> str:
    out = []
    for hit in hits:
        where = f": {hit.declaration}" if hit.declaration else ""
        out += [f"  {hit.path}:{hit.line}{where}: "
                + (f"tracked by {hit.tracked}" if hit.tracked else "untracked"),
                f"    {hit.sentence}"]
    return "\n".join(out + [counts(hits)])


def counts(hits: list[Hit]) -> str:
    by_issue = sum(hit.tracked.startswith("#") for hit in hits)
    by_entry = sum(bool(hit.tracked) for hit in hits) - by_issue
    return (f"{len(hits)} disclaimer(s) under {', '.join(ROOTS)}: {by_issue + by_entry} tracked "
            f"({by_issue} by an issue number, {by_entry} by a premise or witness baseline entry), "
            f"{len(hits) - by_issue - by_entry} untracked")


def status(hits: list[Hit], everywhere: Problems, scope_text: str) -> str:
    open_ = sum(not hit.tracked for hit in hits)
    return (f"{counts(hits)}, of which {open_ - len(everywhere.new)} baselined and "
            f"{len(everywhere.new)} new; {len(everywhere.stale)} stale baseline entr"
            f"{'y' if len(everywhere.stale) == 1 else 'ies'}; checking {scope_text}")


def checker_changed(root: Path, ref: str) -> bool:
    """Whether the change adds or modifies the checker or its baseline."""
    added, modified = cer.ccf.changed_files(root, ref)
    return bool(CHECKER_FILES.intersection(added + modified))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    scope = parser.add_mutually_exclusive_group()
    scope.add_argument("--base", default="origin/main",
                       help="compare the modules changed since the merge base with this revision "
                            "(default origin/main)")
    scope.add_argument("--all", action="store_true", help="compare every module")
    scope.add_argument("--report", action="store_true",
                       help="report every difference from the baseline and succeed")
    scope.add_argument("--list", nargs="?", const="", metavar="PREFIX",
                       help="ignore the baseline and list every disclaimer in the files under the "
                            "path PREFIX with how it is tracked; always succeeds")
    parser.add_argument("--enforce", action="store_true",
                        help="exit 1 on a new disclaimer or a stale entry in a compared module; "
                             "without it the check only reports (CI does not pass it yet)")
    parser.add_argument("--update-baseline", action="store_true",
                        help="remove the stale entries of the compared modules")
    parser.add_argument("--allow-increase", action="store_true",
                        help="with --update-baseline, also record the new disclaimers")
    parser.add_argument("--root", type=Path, default=ROOT, help="the repository to check")
    parser.add_argument("--baseline", type=Path, help="default: the root's baseline file")
    args = parser.parse_args(argv)
    if args.allow_increase and not args.update_baseline:
        parser.error("--allow-increase needs --update-baseline")
    if (args.report or args.list is not None) and (args.update_baseline or args.enforce):
        parser.error("--report and --list do not combine with --update-baseline or --enforce")
    if args.list is not None:
        print(listing(scan(args.root, args.list)))
        return 0
    baseline_path = args.baseline or args.root / BASELINE
    baseline = load_baseline(baseline_path) if baseline_path.exists() else {}
    whole = args.all or args.report
    if not whole and checker_changed(args.root, args.base):
        whole = True
        print("This change edits the disclaimer checker or its baseline, so every module is "
              "compared.")
    paths = None if whole else cer.touched_modules(args.root, args.base)
    scope_text = "every module" if whole else f"{len(paths)} changed module(s)"
    hits = scan(args.root)
    problems = compare(hits, baseline, paths)
    everywhere = problems if paths is None else compare(hits, baseline, None)
    if args.update_baseline:
        if problems.new and not args.allow_increase:
            print(report(Problems(problems.new, [])), file=sys.stderr)
            print("\nThe baseline only shrinks; pass --allow-increase to record new debt on "
                  "purpose.", file=sys.stderr)
            return 1
        updated = update(hits, baseline, paths)
        baseline_path.write_text(baseline_text(updated), encoding="utf-8")
        print(f"Wrote {baseline_path} for {scope_text}: {len(updated)} entries.")
        return 0
    summary = status(hits, everywhere, scope_text)
    if args.report:
        if problems:
            print(report(problems) + "\n")
        print(f"{summary}; report only, nothing is enforced.")
        return 0
    elsewhere = outside(everywhere, problems)
    if elsewhere:
        print("Not compared: differences from the baseline in modules this change does not touch. "
              "The next change to those modules meets them. A change can cause them without "
              "touching those modules, for example by removing an entry of the security-premise "
              "or reduction-witness baseline; if this one did, fix them here.\n\n"
              + report(elsewhere) + "\n")
    if not problems:
        print(f"{summary}; every untracked disclaimer is recorded.")
        return 0
    if args.enforce:
        print(report(problems), file=sys.stderr)
        return 1
    print(report(problems) + f"\n\n{summary}; report only: enforcement is not switched on yet, "
          "and `--enforce` would fail here.")
    if os.environ.get("GITHUB_ACTIONS") == "true":
        print(f"::notice title=Stated limitations::{len(problems.new)} untracked disclaimer(s) "
              f"and {len(problems.stale)} stale baseline entr"
              f"{'y' if len(problems.stale) == 1 else 'ies'} in the compared modules; not "
              "enforced yet, see the step log.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
